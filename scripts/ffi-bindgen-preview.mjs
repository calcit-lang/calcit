import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const GENERATED_HEADER = "Generated by calcit ffi-bindgen preview from Interface IR v1. Do not edit.";

function stableDefinitions(interfaceDocument) {
  return [...interfaceDocument.definitions].sort((left, right) => left.id.localeCompare(right.id));
}

function identifier(value, separator = "_") {
  const normalized = value
    .replace(/([a-z0-9])([A-Z])/gu, `$1${separator}$2`)
    .replace(/[^A-Za-z0-9]+/gu, separator)
    .replace(new RegExp(`${separator}+`, "gu"), separator)
    .replace(new RegExp(`^${separator}|${separator}$`, "gu"), "")
    .toLowerCase();
  if (normalized.length === 0) {
    throw new Error(`cannot derive an identifier from ${JSON.stringify(value)}`);
  }
  return /^[0-9]/u.test(normalized) ? `ffi${separator}${normalized}` : normalized;
}

function rustType(type) {
  switch (type.kind) {
    case "unit":
      return "()";
    case "bool":
      return "bool";
    case "number":
      return "f64";
    case "string":
      return "String";
    case "buffer":
      return "Vec<u8>";
    case "list":
      return `Vec<${rustType(type.item)}>`;
    case "named":
      return `${identifier(type.name, "_")
        .split("_")
        .map((part) => `${part[0].toUpperCase()}${part.slice(1)}`)
        .join("")}${type.arguments.length === 0 ? "" : `<${type.arguments.map(rustType).join(", ")}>`}`;
    default:
      throw new Error(`unsupported Rust preview type ${JSON.stringify(type)}`);
  }
}

function typescriptType(type) {
  switch (type.kind) {
    case "unit":
      return "void";
    case "bool":
      return "boolean";
    case "number":
      return "number";
    case "string":
      return "string";
    case "buffer":
      return "Uint8Array";
    case "list":
      return `ReadonlyArray<${typescriptType(type.item)}>`;
    case "named":
      return `${identifier(type.name, "_")
        .split("_")
        .map((part) => `${part[0].toUpperCase()}${part.slice(1)}`)
        .join("")}${type.arguments.length === 0 ? "" : `<${type.arguments.map(typescriptType).join(", ")}>`}`;
    default:
      throw new Error(`unsupported TypeScript preview type ${JSON.stringify(type)}`);
  }
}

function witType(type, definitionId) {
  switch (type.kind) {
    case "unit":
      return null;
    case "bool":
      return "bool";
    case "number":
      return "float64";
    case "string":
      return "string";
    case "buffer":
      return "list<u8>";
    case "list": {
      const item = witType(type.item, definitionId);
      if (item === null) {
        throw new Error(`${definitionId} uses List<Unit>, which is not a representable WIT value type`);
      }
      return `list<${item}>`;
    }
    case "named":
      throw new Error(
        `${definitionId} uses named type ${type.name}; WIT preview requires exported Struct/Enum/resource declarations that Interface IR v1 does not yet carry`,
      );
    default:
      throw new Error(`${definitionId} uses unsupported WIT preview type ${JSON.stringify(type)}`);
  }
}

function ensurePreviewBinding(definition) {
  if (definition.status !== "supported" || !definition.signature) {
    throw new Error(
      `${definition.id} is ${definition.status}; resolve ${definition.diagnostic_codes.join(", ") || "its Interface IR diagnostics"} before generation`,
    );
  }
  const { lowering } = definition;
  if (lowering.backend !== "native") {
    throw new Error(`${definition.id} uses backend ${lowering.backend ?? "<missing>"}; Phase 0 preview only supports native bindings`);
  }
  if (!lowering.symbol) {
    throw new Error(`${definition.id} does not declare lowering.symbol`);
  }
  if (!/^[A-Za-z_][A-Za-z0-9_]*$/u.test(lowering.symbol)) {
    throw new Error(`${definition.id} uses native symbol ${JSON.stringify(lowering.symbol)}, which is not a portable C identifier`);
  }
  if (lowering.invoke !== "sync" || lowering.transport !== "edn-buffer-v1") {
    throw new Error(
      `${definition.id} uses invoke=${lowering.invoke ?? "<missing>"} transport=${lowering.transport ?? "<missing>"}; Phase 0 preview requires sync edn-buffer-v1`,
    );
  }
}

function renderRust(interfaceDocument, definitions) {
  const traitName = `${identifier(interfaceDocument.package, "_")
    .split("_")
    .map((part) => `${part[0].toUpperCase()}${part.slice(1)}`)
    .join("")}Ffi`;
  const methods = definitions.map((definition) => {
    const parameters = definition.signature.parameters
      .map((parameter) => `arg${parameter.position}: ${rustType(parameter.type)}`)
      .join(", ");
    return `  fn ${identifier(definition.name)}(&self${parameters.length === 0 ? "" : `, ${parameters}`}) -> Result<${rustType(definition.signature.result)}, String>;`;
  });
  const adapters = definitions.flatMap((definition) => {
    const name = identifier(definition.name);
    return [
      "",
      `pub fn ${name}_calcit_adapter(_args: Vec<cirru_edn::Edn>) -> Result<cirru_edn::Edn, String> {`,
      `  todo!("decode edn-buffer-v1 arguments and invoke typed ${traitName}::${name}")`,
      "}",
      "",
      `calcit_native_ffi::export_edn_buffer_method_v1!(${identifier(definition.lowering.symbol)}_calcit_ffi_v1, ${name}_calcit_adapter);`,
    ];
  });
  return [`// ${GENERATED_HEADER}`, `// Package: ${interfaceDocument.package} ${interfaceDocument.package_version}`, "", `pub trait ${traitName} {`, ...methods, "}", ...adapters, ""].join("\n");
}

function renderCalcit(interfaceDocument, definitions) {
  const namespace = `generated.${identifier(interfaceDocument.package, "-").replaceAll("-", ".")}.ffi`;
  const wrappers = definitions.flatMap((definition) => {
    const parameters = definition.signature.parameters.map((parameter) => `arg${parameter.position}`);
    const callArguments = parameters.length === 0 ? "" : ` ${parameters.join(" ")}`;
    return [
      "",
      `defn ${identifier(definition.name, "-")}$raw (dylib-path${callArguments})`,
      `  &call-dylib-edn dylib-path |${definition.lowering.symbol}${callArguments}`,
    ];
  });
  return [`; ${GENERATED_HEADER}`, `; Package: ${interfaceDocument.package} ${interfaceDocument.package_version}`, "", `ns ${namespace}`, ...wrappers, ""].join("\n");
}

function renderTypescript(interfaceDocument, definitions) {
  const declarations = definitions.map((definition) => {
    const parameters = definition.signature.parameters
      .map((parameter) => `arg${parameter.position}: ${typescriptType(parameter.type)}`)
      .join(", ");
    return `export declare function ${identifier(definition.name)}(${parameters}): ${typescriptType(definition.signature.result)};`;
  });
  return [`// ${GENERATED_HEADER}`, `// Package: ${interfaceDocument.package} ${interfaceDocument.package_version}`, "", ...declarations, ""].join("\n");
}

function renderWit(interfaceDocument, definitions) {
  const packageName = identifier(interfaceDocument.package, "-");
  const functions = definitions.map((definition) => {
    const parameters = definition.signature.parameters
      .map((parameter) => `arg${parameter.position}: ${witType(parameter.type, definition.id)}`)
      .join(", ");
    const result = witType(definition.signature.result, definition.id);
    return `  ${identifier(definition.name, "-")}: func(${parameters})${result === null ? "" : ` -> ${result}`};`;
  });
  return [
    `// ${GENERATED_HEADER}`,
    `package calcit:${packageName}@${interfaceDocument.package_version};`,
    "",
    `interface ${packageName} {`,
    ...functions,
    "}",
    "",
    `world ${packageName}-world {`,
    `  export ${packageName};`,
    "}",
    "",
  ].join("\n");
}

export function normalizeInterface(document) {
  const interfaceDocument = document?.command === "ffi.export" ? document.data?.interface : document;
  if (!interfaceDocument || interfaceDocument.version !== 1 || !Array.isArray(interfaceDocument.definitions)) {
    throw new Error("expected an Interface IR v1 document or calcit ffi.export JSON envelope");
  }
  if (typeof interfaceDocument.package !== "string" || typeof interfaceDocument.package_version !== "string") {
    throw new Error("Interface IR package and package_version must be strings");
  }
  return interfaceDocument;
}

export function generatePreview(document) {
  const interfaceDocument = normalizeInterface(document);
  const definitions = stableDefinitions(interfaceDocument);
  if (definitions.length === 0) {
    throw new Error("Interface IR contains no definitions to generate");
  }
  definitions.forEach(ensurePreviewBinding);
  const slug = identifier(interfaceDocument.package, "-");
  return new Map([
    [`${slug}.ffi.rs`, renderRust(interfaceDocument, definitions)],
    [`${slug}.ffi.cirru`, renderCalcit(interfaceDocument, definitions)],
    [`${slug}.d.ts`, renderTypescript(interfaceDocument, definitions)],
    [`${slug}.wit`, renderWit(interfaceDocument, definitions)],
  ]);
}

export async function writePreview(document, outputDirectory) {
  const interfaceDocument = normalizeInterface(document);
  const outputs = generatePreview(interfaceDocument);
  await mkdir(outputDirectory, { recursive: true });
  const generated = [];
  for (const [name, content] of outputs) {
    await writeFile(path.join(outputDirectory, name), content);
    generated.push({
      path: name,
      sha256: createHash("sha256").update(content).digest("hex"),
    });
  }
  const manifest = {
    schema_version: 1,
    interface_version: interfaceDocument.version,
    package: interfaceDocument.package,
    package_version: interfaceDocument.package_version,
    generated,
  };
  await writeFile(path.join(outputDirectory, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);
  return manifest;
}

function parseArguments(argv) {
  const options = { input: null, output: null };
  for (let index = 0; index < argv.length; index += 1) {
    switch (argv[index]) {
      case "--input":
        options.input = argv[++index];
        break;
      case "--out":
        options.output = argv[++index];
        break;
      default:
        throw new Error(`unknown argument ${argv[index]}`);
    }
  }
  if (!options.input || !options.output) {
    throw new Error("usage: node scripts/ffi-bindgen-preview.mjs --input <interface.json> --out <directory>");
  }
  return options;
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);
if (isMain) {
  try {
    const options = parseArguments(process.argv.slice(2));
    const raw = options.input === "-" ? await new Promise((resolve, reject) => {
      let content = "";
      process.stdin.setEncoding("utf8");
      process.stdin.on("data", (chunk) => {
        content += chunk;
      });
      process.stdin.on("end", () => resolve(content));
      process.stdin.on("error", reject);
    }) : await readFile(options.input, "utf8");
    const manifest = await writePreview(JSON.parse(raw), options.output);
    process.stdout.write(`${JSON.stringify(manifest, null, 2)}\n`);
  } catch (error) {
    process.stderr.write(`ffi-bindgen preview failed: ${error instanceof Error ? error.message : String(error)}\n`);
    process.exitCode = 1;
  }
}
