import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

function generatedHeader(interfaceDocument) {
  return `Generated by calcit ffi-bindgen preview from Interface IR v${interfaceDocument.version}. Do not edit.`;
}

function stableDefinitions(interfaceDocument) {
  return [...interfaceDocument.definitions].sort((left, right) => left.id.localeCompare(right.id));
}

function stableDeclarations(interfaceDocument) {
  return [...interfaceDocument.declarations].sort((left, right) => left.id.localeCompare(right.id));
}

function declarationMap(interfaceDocument) {
  const declarations = new Map();
  for (const declaration of stableDeclarations(interfaceDocument)) {
    if (declarations.has(declaration.id)) {
      throw new Error(`duplicated Interface IR declaration ${declaration.id}`);
    }
    declarations.set(declaration.id, declaration);
  }
  return declarations;
}

function identifier(value, separator = "_") {
  const normalized = value
    .replace(/([a-z0-9])([A-Z])/gu, `$1${separator}$2`)
    .replace(/[^A-Za-z0-9]+/gu, separator)
    .replace(new RegExp(`${separator}+`, "gu"), separator)
    .replace(new RegExp(`^${separator}|${separator}$`, "gu"), "")
    .toLowerCase();
  if (normalized.length === 0) {
    throw new Error(`cannot derive an identifier from ${JSON.stringify(value)}`);
  }
  return /^[0-9]/u.test(normalized) ? `ffi${separator}${normalized}` : normalized;
}

function pascalIdentifier(value) {
  return identifier(value, "_")
    .split("_")
    .map((part) => `${part[0].toUpperCase()}${part.slice(1)}`)
    .join("");
}

function declarationTypeName(id) {
  return pascalIdentifier(id);
}

function typeParameterName(name) {
  const normalized = name.replace(/[^A-Za-z0-9_]+/gu, "");
  if (!/^[A-Za-z_][A-Za-z0-9_]*$/u.test(normalized)) {
    throw new Error(`invalid Interface IR type parameter ${JSON.stringify(name)}`);
  }
  return normalized;
}

function requireDeclaration(type, declarations, definitionId) {
  const declaration = declarations.get(type.id);
  if (!declaration) {
    throw new Error(`${definitionId} references missing Interface IR declaration ${type.id}`);
  }
  if (declaration.kind !== type.kind) {
    throw new Error(`${definitionId} references ${type.id} as ${type.kind}, but the declaration is ${declaration.kind}`);
  }
  if (declaration.type_parameters.length !== type.arguments.length) {
    throw new Error(
      `${definitionId} applies ${type.arguments.length} argument(s) to ${type.id}, which declares ${declaration.type_parameters.length}`,
    );
  }
  return declaration;
}

function rustType(type, declarations, definitionId) {
  switch (type.kind) {
    case "unit":
      return "()";
    case "bool":
      return "bool";
    case "number":
      return "f64";
    case "string":
      return "String";
    case "buffer":
      return "Vec<u8>";
    case "list":
      return `Vec<${rustType(type.item, declarations, definitionId)}>`;
    case "option":
      return `Option<${rustType(type.item, declarations, definitionId)}>`;
    case "result":
      return `Result<${rustType(type.ok, declarations, definitionId)}, ${rustType(type.error, declarations, definitionId)}>`;
    case "struct":
    case "enum":
      requireDeclaration(type, declarations, definitionId);
      return `${declarationTypeName(type.id)}${
        type.arguments.length === 0
          ? ""
          : `<${type.arguments.map((argument) => rustType(argument, declarations, definitionId)).join(", ")}>`
      }`;
    case "type-parameter":
      return typeParameterName(type.name);
    default:
      throw new Error(`unsupported Rust preview type ${JSON.stringify(type)}`);
  }
}

function typescriptType(type, declarations, definitionId) {
  switch (type.kind) {
    case "unit":
      return "void";
    case "bool":
      return "boolean";
    case "number":
      return "number";
    case "string":
      return "string";
    case "buffer":
      return "Uint8Array";
    case "list":
      return `ReadonlyArray<${typescriptType(type.item, declarations, definitionId)}>`;
    case "option":
      return `{ readonly tag: "none" } | { readonly tag: "some"; readonly value: ${typescriptType(type.item, declarations, definitionId)} }`;
    case "result":
      return `{ readonly tag: "ok"; readonly value: ${typescriptType(type.ok, declarations, definitionId)} } | { readonly tag: "err"; readonly error: ${typescriptType(type.error, declarations, definitionId)} }`;
    case "struct":
    case "enum":
      requireDeclaration(type, declarations, definitionId);
      return `${declarationTypeName(type.id)}${
        type.arguments.length === 0
          ? ""
          : `<${type.arguments.map((argument) => typescriptType(argument, declarations, definitionId)).join(", ")}>`
      }`;
    case "type-parameter":
      return typeParameterName(type.name);
    default:
      throw new Error(`unsupported TypeScript preview type ${JSON.stringify(type)}`);
  }
}

function witType(type, definitionId, declarations) {
  switch (type.kind) {
    case "unit":
      return null;
    case "bool":
      return "bool";
    case "number":
      return "float64";
    case "string":
      return "string";
    case "buffer":
      return "list<u8>";
    case "list": {
      const item = witType(type.item, definitionId, declarations);
      if (item === null) {
        throw new Error(`${definitionId} uses List<Unit>, which is not a representable WIT value type`);
      }
      return `list<${item}>`;
    }
    case "option": {
      const item = witType(type.item, definitionId, declarations);
      if (item === null) {
        throw new Error(`${definitionId} uses Option<Unit>, which is not a representable WIT value type`);
      }
      return `option<${item}>`;
    }
    case "result": {
      const ok = witType(type.ok, definitionId, declarations);
      const error = witType(type.error, definitionId, declarations);
      if (ok === null && error === null) {
        return "result";
      }
      if (error === null) {
        return `result<${ok}>`;
      }
      if (ok === null) {
        return `result<_, ${error}>`;
      }
      return `result<${ok}, ${error}>`;
    }
    case "struct":
    case "enum":
      requireDeclaration(type, declarations, definitionId);
      if (type.arguments.length > 0) {
        throw new Error(`${definitionId} uses generic declaration ${type.id}; the WIT preview requires a monomorphic declaration`);
      }
      return identifier(type.id, "-");
    case "type-parameter":
      throw new Error(`${definitionId} exposes type parameter ${type.name}; the WIT preview requires monomorphic declarations`);
    default:
      throw new Error(`${definitionId} uses unsupported WIT preview type ${JSON.stringify(type)}`);
  }
}

function ensurePreviewBinding(definition) {
  if (definition.status !== "supported" || !definition.signature) {
    throw new Error(
      `${definition.id} is ${definition.status}; resolve ${definition.diagnostic_codes.join(", ") || "its Interface IR diagnostics"} before generation`,
    );
  }
  const { lowering } = definition;
  if (lowering.backend !== "native") {
    throw new Error(`${definition.id} uses backend ${lowering.backend ?? "<missing>"}; Phase 0 preview only supports native bindings`);
  }
  if (!lowering.symbol) {
    throw new Error(`${definition.id} does not declare lowering.symbol`);
  }
  if (!/^[A-Za-z_][A-Za-z0-9_]*$/u.test(lowering.symbol)) {
    throw new Error(`${definition.id} uses native symbol ${JSON.stringify(lowering.symbol)}, which is not a portable C identifier`);
  }
  if (lowering.invoke !== "sync" || lowering.transport !== "edn-buffer-v1") {
    throw new Error(
      `${definition.id} uses invoke=${lowering.invoke ?? "<missing>"} transport=${lowering.transport ?? "<missing>"}; Phase 0 preview requires sync edn-buffer-v1`,
    );
  }
}

function ensureUniqueGeneratedIdentifiers(items, target, generatedIdentifier) {
  const owners = new Map();
  for (const item of items) {
    const generated = generatedIdentifier(item);
    const previous = owners.get(generated);
    if (previous) {
      throw new Error(
        `generated ${target} identifier ${JSON.stringify(generated)} collides between ${previous.id} and ${item.id}`,
      );
    }
    owners.set(generated, item);
  }
}

function ensureGeneratedIdentifiers(definitions, declarations) {
  ensureUniqueGeneratedIdentifiers(definitions, "Rust/TypeScript definition", (definition) => identifier(definition.name));
  ensureUniqueGeneratedIdentifiers(definitions, "Calcit/WIT definition", (definition) => identifier(definition.name, "-"));
  ensureUniqueGeneratedIdentifiers(definitions, "Rust native symbol", (definition) => identifier(definition.lowering.symbol));
  ensureUniqueGeneratedIdentifiers(declarations, "Rust/TypeScript declaration", (declaration) => declarationTypeName(declaration.id));
  ensureUniqueGeneratedIdentifiers(declarations, "WIT declaration", (declaration) => identifier(declaration.id, "-"));
}

function renderRustDeclarations(interfaceDocument, declarations) {
  return stableDeclarations(interfaceDocument).flatMap((declaration) => {
    const name = declarationTypeName(declaration.id);
    const generics =
      declaration.type_parameters.length === 0
        ? ""
        : `<${declaration.type_parameters.map(typeParameterName).join(", ")}>`;
    if (declaration.kind === "struct") {
      return [
        "#[derive(Debug, Clone, PartialEq)]",
        `pub struct ${name}${generics} {`,
        ...declaration.fields.map(
          (field) => `  pub ${identifier(field.name)}: ${rustType(field.type, declarations, declaration.id)},`,
        ),
        "}",
        "",
      ];
    }
    if (declaration.kind === "enum") {
      return [
        "#[derive(Debug, Clone, PartialEq)]",
        `pub enum ${name}${generics} {`,
        ...declaration.variants.map((variant) => {
          const variantName = pascalIdentifier(variant.name);
          const payload = variant.payload.map((item) => rustType(item, declarations, declaration.id));
          return `  ${variantName}${payload.length === 0 ? "" : `(${payload.join(", ")})`},`;
        }),
        "}",
        "",
      ];
    }
    throw new Error(`unsupported Interface IR declaration ${JSON.stringify(declaration)}`);
  });
}

function renderRust(interfaceDocument, definitions, declarations) {
  const traitName = `${pascalIdentifier(interfaceDocument.package)}Ffi`;
  const methods = definitions.map((definition) => {
    const parameters = definition.signature.parameters
      .map((parameter) => `arg${parameter.position}: ${rustType(parameter.type, declarations, definition.id)}`)
      .join(", ");
    return `  fn ${identifier(definition.name)}(&self${parameters.length === 0 ? "" : `, ${parameters}`}) -> Result<${rustType(definition.signature.result, declarations, definition.id)}, String>;`;
  });
  const adapters = definitions.flatMap((definition) => {
    const name = identifier(definition.name);
    return [
      "",
      `pub fn ${name}_calcit_adapter(_args: Vec<cirru_edn::Edn>) -> Result<cirru_edn::Edn, String> {`,
      `  todo!("decode edn-buffer-v1 arguments and invoke typed ${traitName}::${name}")`,
      "}",
      "",
      `calcit_native_ffi::export_edn_buffer_method_v1!(${identifier(definition.lowering.symbol)}_calcit_ffi_v1, ${name}_calcit_adapter);`,
    ];
  });
  return [
    `// ${generatedHeader(interfaceDocument)}`,
    `// Package: ${interfaceDocument.package} ${interfaceDocument.package_version}`,
    "",
    ...renderRustDeclarations(interfaceDocument, declarations),
    `pub trait ${traitName} {`,
    ...methods,
    "}",
    ...adapters,
    "",
  ].join("\n");
}

function renderCalcit(interfaceDocument, definitions) {
  const namespace = `generated.${identifier(interfaceDocument.package, "-").replaceAll("-", ".")}.ffi`;
  const wrappers = definitions.flatMap((definition) => {
    const parameters = definition.signature.parameters.map((parameter) => `arg${parameter.position}`);
    const callArguments = parameters.length === 0 ? "" : ` ${parameters.join(" ")}`;
    return [
      "",
      `defn ${identifier(definition.name, "-")}$raw (dylib-path${callArguments})`,
      `  &call-dylib-edn dylib-path |${definition.lowering.symbol}${callArguments}`,
    ];
  });
  return [`; ${generatedHeader(interfaceDocument)}`, `; Package: ${interfaceDocument.package} ${interfaceDocument.package_version}`, "", `ns ${namespace}`, ...wrappers, ""].join("\n");
}

function renderTypescriptDeclarations(interfaceDocument, declarations) {
  return stableDeclarations(interfaceDocument).flatMap((declaration) => {
    const name = declarationTypeName(declaration.id);
    const generics =
      declaration.type_parameters.length === 0
        ? ""
        : `<${declaration.type_parameters.map(typeParameterName).join(", ")}>`;
    if (declaration.kind === "struct") {
      return [
        `export interface ${name}${generics} {`,
        ...declaration.fields.map(
          (field) => `  readonly ${identifier(field.name)}: ${typescriptType(field.type, declarations, declaration.id)};`,
        ),
        "}",
        "",
      ];
    }
    if (declaration.kind === "enum") {
      const variants = declaration.variants.map((variant) => {
        const payload = variant.payload.map((item) => typescriptType(item, declarations, declaration.id));
        return payload.length === 0
          ? `{ readonly tag: "${identifier(variant.name, "-")}" }`
          : `{ readonly tag: "${identifier(variant.name, "-")}"; readonly payload: readonly [${payload.join(", ")}] }`;
      });
      return [`export type ${name}${generics} =`, ...variants.map((variant, index) => `  ${index === 0 ? "" : "| "}${variant}`), ";", ""];
    }
    throw new Error(`unsupported Interface IR declaration ${JSON.stringify(declaration)}`);
  });
}

function renderTypescript(interfaceDocument, definitions, declarations) {
  const apiDeclarations = definitions.map((definition) => {
    const parameters = definition.signature.parameters
      .map((parameter) => `arg${parameter.position}: ${typescriptType(parameter.type, declarations, definition.id)}`)
      .join(", ");
    return `export declare function ${identifier(definition.name)}(${parameters}): ${typescriptType(definition.signature.result, declarations, definition.id)};`;
  });
  return [
    `// ${generatedHeader(interfaceDocument)}`,
    `// Package: ${interfaceDocument.package} ${interfaceDocument.package_version}`,
    "",
    ...renderTypescriptDeclarations(interfaceDocument, declarations),
    ...apiDeclarations,
    "",
  ].join("\n");
}

function renderWitDeclarations(interfaceDocument, declarations) {
  return stableDeclarations(interfaceDocument).flatMap((declaration) => {
    if (declaration.type_parameters.length > 0) {
      throw new Error(`${declaration.id} is generic; the WIT preview requires monomorphic declarations`);
    }
    const name = identifier(declaration.id, "-");
    if (declaration.kind === "struct") {
      return [
        `  record ${name} {`,
        ...declaration.fields.map((field) => {
          const type = witType(field.type, declaration.id, declarations);
          if (type === null) {
            throw new Error(`${declaration.id}.${field.name} uses Unit, which is not a representable WIT record field`);
          }
          return `    ${identifier(field.name, "-")}: ${type},`;
        }),
        "  }",
        "",
      ];
    }
    if (declaration.kind === "enum") {
      return [
        `  variant ${name} {`,
        ...declaration.variants.map((variant) => {
          const payload = variant.payload.map((item) => witType(item, declaration.id, declarations));
          if (payload.some((item) => item === null)) {
            throw new Error(`${declaration.id}.${variant.name} contains Unit in a WIT variant payload`);
          }
          const type = payload.length < 2 ? payload[0] : `tuple<${payload.join(", ")}>`;
          return `    ${identifier(variant.name, "-")}${type === undefined ? "" : `(${type})`},`;
        }),
        "  }",
        "",
      ];
    }
    throw new Error(`unsupported Interface IR declaration ${JSON.stringify(declaration)}`);
  });
}

function renderWit(interfaceDocument, definitions, declarations) {
  const packageName = identifier(interfaceDocument.package, "-");
  const functions = definitions.map((definition) => {
    const parameters = definition.signature.parameters
      .map((parameter) => {
        const type = witType(parameter.type, definition.id, declarations);
        if (type === null) {
          throw new Error(`${definition.id} parameter ${parameter.position} uses Unit, which is not a representable WIT parameter type`);
        }
        return `arg${parameter.position}: ${type}`;
      })
      .join(", ");
    const result = witType(definition.signature.result, definition.id, declarations);
    return `  ${identifier(definition.name, "-")}: func(${parameters})${result === null ? "" : ` -> ${result}`};`;
  });
  return [
    `// ${generatedHeader(interfaceDocument)}`,
    `package calcit:${packageName}@${interfaceDocument.package_version};`,
    "",
    `interface ${packageName} {`,
    ...renderWitDeclarations(interfaceDocument, declarations),
    ...functions,
    "}",
    "",
    `world ${packageName}-world {`,
    `  export ${packageName};`,
    "}",
    "",
  ].join("\n");
}

export function normalizeInterface(document) {
  const interfaceDocument = document?.command === "ffi.export" ? document.data?.interface : document;
  if (!interfaceDocument || interfaceDocument.version !== 2 || !Array.isArray(interfaceDocument.definitions)) {
    throw new Error("expected an Interface IR v2 document or calcit ffi.export JSON envelope");
  }
  if (typeof interfaceDocument.package !== "string" || typeof interfaceDocument.package_version !== "string") {
    throw new Error("Interface IR package and package_version must be strings");
  }
  if (!Array.isArray(interfaceDocument.declarations)) {
    throw new Error("Interface IR v2 declarations must be an array");
  }
  return interfaceDocument;
}

export function generatePreview(document) {
  const interfaceDocument = normalizeInterface(document);
  const definitions = stableDefinitions(interfaceDocument);
  if (definitions.length === 0) {
    throw new Error("Interface IR contains no definitions to generate");
  }
  definitions.forEach(ensurePreviewBinding);
  const declarations = declarationMap(interfaceDocument);
  ensureGeneratedIdentifiers(definitions, [...declarations.values()]);
  const slug = identifier(interfaceDocument.package, "-");
  return new Map([
    [`${slug}.ffi.rs`, renderRust(interfaceDocument, definitions, declarations)],
    [`${slug}.ffi.cirru`, renderCalcit(interfaceDocument, definitions)],
    [`${slug}.d.ts`, renderTypescript(interfaceDocument, definitions, declarations)],
    [`${slug}.wit`, renderWit(interfaceDocument, definitions, declarations)],
  ]);
}

export async function writePreview(document, outputDirectory) {
  const interfaceDocument = normalizeInterface(document);
  const outputs = generatePreview(interfaceDocument);
  await mkdir(outputDirectory, { recursive: true });
  const generated = [];
  for (const [name, content] of outputs) {
    await writeFile(path.join(outputDirectory, name), content);
    generated.push({
      path: name,
      sha256: createHash("sha256").update(content).digest("hex"),
    });
  }
  const manifest = {
    schema_version: 1,
    interface_version: interfaceDocument.version,
    package: interfaceDocument.package,
    package_version: interfaceDocument.package_version,
    generated,
  };
  await writeFile(path.join(outputDirectory, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);
  return manifest;
}

function parseArguments(argv) {
  const options = { input: null, output: null };
  for (let index = 0; index < argv.length; index += 1) {
    switch (argv[index]) {
      case "--input":
        options.input = argv[++index];
        break;
      case "--out":
        options.output = argv[++index];
        break;
      default:
        throw new Error(`unknown argument ${argv[index]}`);
    }
  }
  if (!options.input || !options.output) {
    throw new Error("usage: node scripts/ffi-bindgen-preview.mjs --input <interface.json> --out <directory>");
  }
  return options;
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);
if (isMain) {
  try {
    const options = parseArguments(process.argv.slice(2));
    const raw = options.input === "-" ? await new Promise((resolve, reject) => {
      let content = "";
      process.stdin.setEncoding("utf8");
      process.stdin.on("data", (chunk) => {
        content += chunk;
      });
      process.stdin.on("end", () => resolve(content));
      process.stdin.on("error", reject);
    }) : await readFile(options.input, "utf8");
    const manifest = await writePreview(JSON.parse(raw), options.output);
    process.stdout.write(`${JSON.stringify(manifest, null, 2)}\n`);
  } catch (error) {
    process.stderr.write(`ffi-bindgen preview failed: ${error instanceof Error ? error.message : String(error)}\n`);
    process.exitCode = 1;
  }
}
