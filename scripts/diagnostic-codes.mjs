// Generates docs/diagnostic-codes.md from the diagnostic code literals in src/.
// Usage: node scripts/diagnostic-codes.mjs --write|--check
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const mode = process.argv[2];
if (mode !== "--write" && mode !== "--check") {
  throw new Error("usage: node scripts/diagnostic-codes.mjs --write|--check");
}

const repository = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourceRoot = join(repository, "src");
const outputPath = join(repository, "docs/diagnostic-codes.md");

// Test-only sources assert on codes but do not emit them.
const skippedDirectories = new Set([join(sourceRoot, "bin/cr_tests")]);

function rustFiles(directory) {
  const files = [];
  for (const name of readdirSync(directory).sort()) {
    const path = join(directory, name);
    if (statSync(path).isDirectory()) {
      if (!skippedDirectories.has(path)) files.push(...rustFiles(path));
    } else if (name.endsWith(".rs")) {
      files.push(path);
    }
  }
  return files;
}

// Drop inline `#[cfg(test)]` modules, which conventionally close each file.
function productionSource(text) {
  const marker = text.search(/^#\[cfg\(test\)\]\s*\n\s*mod \w+/m);
  return marker === -1 ? text : text.slice(0, marker);
}

const codePattern = /"([EWIP]_[A-Z][A-Z0-9_]*[A-Z0-9])"/g;
const codes = new Map();
for (const file of rustFiles(sourceRoot)) {
  const source = productionSource(readFileSync(file, "utf8"));
  for (const match of source.matchAll(codePattern)) {
    const code = match[1];
    const files = codes.get(code) ?? new Set();
    files.add(relative(repository, file));
    codes.set(code, files);
  }
}

const channels = [
  ["E_", "Error：阻断检查、运行、测试与 codegen"],
  ["W_", "Warning：列在 `Notes:` 或按需分析报告中，检查仍通过"],
  ["I_", "Info：报告与证据，不影响检查结果"],
  ["P_", "按需分析：只在 `--warn-dyn-method` 或 `analyze weak-types --only dynamic-method` 下报告"],
];

const lines = [
  "<!-- Generated by scripts/diagnostic-codes.mjs; run `yarn generate-diagnostic-codes` after adding or removing a code. -->",
  "# 诊断编码索引",
  "",
  `源码中共有 **${codes.size}** 个诊断编码。前缀表示通道（#2698）：`,
  "",
  "| 前缀 | 含义 |",
  "| --- | --- |",
  ...channels.map(([prefix, meaning]) => `| \`${prefix}\` | ${meaning} |`),
  "",
  "同名的 `E_` / `W_` 成对编码表示同一检查在不同策略下的两种结果（例如 feature policy 为 `:error` 与 `:warn`）。消息正文在源码中，本表只列出编码及其所在文件，方便按编码搜索。",
];
for (const [prefix] of channels) {
  const entries = [...codes.entries()].filter(([code]) => code.startsWith(prefix)).sort(([a], [b]) => a.localeCompare(b));
  lines.push("", `## \`${prefix}\`（${entries.length}）`, "", "| 编码 | 源文件 |", "| --- | --- |");
  for (const [code, files] of entries) {
    lines.push(`| \`${code}\` | ${[...files].sort().map((file) => `\`${file}\``).join("<br>")} |`);
  }
}
const output = `${lines.join("\n")}\n`;

if (mode === "--write") {
  writeFileSync(outputPath, output);
  console.log(`wrote ${relative(repository, outputPath)} (${codes.size} codes)`);
} else {
  let current = "";
  try {
    current = readFileSync(outputPath, "utf8");
  } catch {
    // treated as out of date below
  }
  if (current !== output) {
    console.error(
      "docs/diagnostic-codes.md is out of date with the diagnostic codes in src/; run `yarn generate-diagnostic-codes` and commit the result",
    );
    process.exit(1);
  }
  console.log(`docs/diagnostic-codes.md matches src/ (${codes.size} codes)`);
}
