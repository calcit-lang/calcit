//! Compile-time attachment of `defimpl Type Trait` (#2727).
//!
//! A top-level `defimpl Coalescer CoalescerOps …` names the struct or enum it
//! implements. When the program is loaded, every such impl is attached to the
//! definition of its type by rewriting that definition's code into the
//! `impl-traits` shape the checker and all backends already understand:
//!
//! ```cirru
//! defstruct Coalescer (:delay-ms Number)
//! ; is loaded as
//! calcit.core/impl-traits (defstruct Coalescer (:delay-ms Number)) Coalescer:CoalescerOps
//! ```
//!
//! The generated head is the qualified `calcit.core/impl-traits` symbol, so the
//! rewrite can be told apart from attachment written by hand and undone before
//! it is applied again on reload. An impl lives in the namespace of its type or
//! of its trait (`E_ORPHAN_IMPL`), and one type has at most one impl of a trait
//! (`E_DUPLICATE_TRAIT_IMPL`).

use std::collections::HashMap;
use std::sync::Arc;

use crate::calcit::{self, Calcit};

use super::{ImportRule, ProgramCodeData, ProgramFileData};

pub(crate) const ORPHAN_IMPL_ERROR: &str = "E_ORPHAN_IMPL";
const DUPLICATE_TRAIT_IMPL_ERROR: &str = "E_DUPLICATE_TRAIT_IMPL";
/// Head of a generated attachment. Hand-written attachment uses `impl-traits`.
pub(crate) const GENERATED_ATTACH_HEAD: &str = "calcit.core/impl-traits";

type DefKey = (Arc<str>, Arc<str>);

fn symbol_name(form: &Calcit) -> Option<&str> {
  match form {
    Calcit::Symbol { sym, .. } => Some(sym.as_ref()),
    _ => None,
  }
}

fn head_is(form: &Calcit, name: &str) -> bool {
  matches!(form, Calcit::List(items) if items.first().and_then(symbol_name) == Some(name))
}

/// `(defimpl Type Trait …)`: the type and trait symbols.
pub(crate) fn defimpl_type_and_trait(code: &Calcit) -> Option<(&str, &str)> {
  let Calcit::List(items) = code else { return None };
  if items.first().and_then(symbol_name) != Some("defimpl") {
    return None;
  }
  Some((items.get(1).and_then(symbol_name)?, items.get(2).and_then(symbol_name)?))
}

/// Resolve a symbol written in `ns` to the definition it names.
fn resolve_in(program: &ProgramCodeData, ns: &str, file: &ProgramFileData, name: &str) -> Option<DefKey> {
  if let Some((prefix, def)) = name.split_once('/') {
    let target_ns = match file.import_map.get(prefix).map(AsRef::as_ref) {
      Some(ImportRule::NsAs(target)) => target.to_owned(),
      _ => Arc::from(prefix),
    };
    return program
      .get(&target_ns)
      .is_some_and(|target| target.defs.contains_key(def))
      .then(|| (target_ns, Arc::from(def)));
  }
  if file.defs.contains_key(name) {
    return Some((Arc::from(ns), Arc::from(name)));
  }
  match file.import_map.get(name).map(AsRef::as_ref) {
    Some(ImportRule::NsReferDef(target_ns, target_def)) => Some((target_ns.to_owned(), target_def.to_owned())),
    _ => program
      .get(calcit::CORE_NS)
      .is_some_and(|core| core.defs.contains_key(name))
      .then(|| (Arc::from(calcit::CORE_NS), Arc::from(name))),
  }
}

/// Whether the code carries an attachment generated by this module.
fn is_generated_attachment(code: &Calcit) -> bool {
  let Calcit::List(items) = code else { return false };
  match items.first().and_then(symbol_name) {
    Some(GENERATED_ATTACH_HEAD) => true,
    Some("def") => items.get(2).is_some_and(|value| head_is(value, GENERATED_ATTACH_HEAD)),
    _ => false,
  }
}

/// Undo a generated attachment, giving back the code as written.
pub(crate) fn strip_generated_attachment(code: &Calcit) -> Calcit {
  let Calcit::List(items) = code else { return code.to_owned() };
  if items.first().and_then(symbol_name) == Some(GENERATED_ATTACH_HEAD) {
    return items.get(1).cloned().unwrap_or_else(|| code.to_owned());
  }
  if items.first().and_then(symbol_name) == Some("def")
    && let Some(value) = items.get(2)
    && head_is(value, GENERATED_ATTACH_HEAD)
  {
    let mut rebuilt: Vec<Calcit> = items.iter().cloned().collect();
    rebuilt[2] = strip_generated_attachment(value);
    return Calcit::from(rebuilt);
  }
  code.to_owned()
}

/// Definitions that currently carry a generated attachment, with that code.
pub(crate) fn generated_attachments(program: &ProgramCodeData) -> HashMap<DefKey, Calcit> {
  let mut found = HashMap::new();
  for (ns, file) in program {
    for (def, entry) in &file.defs {
      if is_generated_attachment(&entry.code) {
        found.insert((ns.to_owned(), def.to_owned()), entry.code.to_owned());
      }
    }
  }
  found
}

/// Whether the code, as written, defines a struct or enum.
fn defines_nominal_type(code: &Calcit) -> bool {
  let Calcit::List(items) = code else { return false };
  match items.first().and_then(symbol_name) {
    Some("defstruct" | "defenum") => true,
    Some("def") => items.get(2).is_some_and(defines_nominal_type),
    Some("impl-traits") => items.get(1).is_some_and(defines_nominal_type),
    _ => false,
  }
}

fn attach(code: &Calcit, impls: &[Calcit]) -> Calcit {
  let wrap = |value: &Calcit| {
    let mut items = vec![Calcit::Symbol {
      sym: Arc::from(GENERATED_ATTACH_HEAD),
      info: match value {
        Calcit::List(xs) => match xs.first() {
          Some(Calcit::Symbol { info, .. }) => info.to_owned(),
          _ => Arc::new(calcit::CalcitSymbolInfo {
            at_ns: Arc::from(""),
            at_def: Arc::from(""),
          }),
        },
        _ => Arc::new(calcit::CalcitSymbolInfo {
          at_ns: Arc::from(""),
          at_def: Arc::from(""),
        }),
      },
      location: None,
    }];
    items.push(value.to_owned());
    items.extend(impls.iter().cloned());
    Calcit::from(items)
  };
  if let Calcit::List(items) = code
    && items.first().and_then(symbol_name) == Some("def")
    && let Some(value) = items.get(2)
  {
    let mut rebuilt: Vec<Calcit> = items.iter().cloned().collect();
    rebuilt[2] = wrap(value);
    return Calcit::from(rebuilt);
  }
  wrap(code)
}

/// A reference to the impl definition, written from the type's namespace.
fn impl_reference(code: &Calcit, impl_ns: &str, impl_def: &str, type_ns: &str) -> Calcit {
  let info = match code {
    Calcit::List(items) => match items.first() {
      Some(Calcit::Symbol { info, .. }) => info.to_owned(),
      _ => Arc::new(calcit::CalcitSymbolInfo {
        at_ns: Arc::from(type_ns),
        at_def: Arc::from(""),
      }),
    },
    _ => Arc::new(calcit::CalcitSymbolInfo {
      at_ns: Arc::from(type_ns),
      at_def: Arc::from(""),
    }),
  };
  let sym = if impl_ns == type_ns {
    Arc::from(impl_def)
  } else {
    Arc::from(format!("{impl_ns}/{impl_def}"))
  };
  Calcit::Symbol { sym, info, location: None }
}

/// Attach every `defimpl Type Trait` in `program` to its type definition.
pub(crate) fn attach_source_impls(program: &mut ProgramCodeData) -> Result<Vec<DefKey>, String> {
  // Start from the code as written, so a reload attaches afresh.
  for file in program.values_mut() {
    for entry in file.defs.values_mut() {
      if is_generated_attachment(&entry.code) {
        entry.code = strip_generated_attachment(&entry.code);
      }
    }
  }

  let mut by_type: HashMap<DefKey, Vec<(DefKey, DefKey)>> = HashMap::new();
  let mut namespaces: Vec<&Arc<str>> = program.keys().collect();
  namespaces.sort();
  for ns in namespaces {
    let file = &program[ns];
    let mut defs: Vec<&Arc<str>> = file.defs.keys().collect();
    defs.sort();
    for def in defs {
      let Some((type_name, trait_name)) = defimpl_type_and_trait(&file.defs[def].code) else {
        continue;
      };
      let Some(type_key) = resolve_in(program, ns, file, type_name) else {
        continue;
      };
      let type_is_nominal = program
        .get(&type_key.0)
        .and_then(|type_file| type_file.defs.get(&type_key.1))
        .is_some_and(|entry| defines_nominal_type(&entry.code));
      if !type_is_nominal {
        // `(defimpl ImplName Trait …)` names the impl, not a type.
        continue;
      }
      let trait_key = resolve_in(program, ns, file, trait_name).unwrap_or_else(|| (ns.to_owned(), Arc::from(trait_name)));
      if ns.as_ref() != type_key.0.as_ref() && ns.as_ref() != trait_key.0.as_ref() {
        return Err(format!(
          "[{ORPHAN_IMPL_ERROR}] {ns}/{def}: `defimpl {type_name} {trait_name}` must be written in the namespace of the type (`{}`) or of the trait (`{}`), so every implementation of a type can be found; move it to one of them",
          type_key.0, trait_key.0
        ));
      }
      let impls = by_type.entry(type_key.clone()).or_default();
      if let Some(((other_ns, other_def), _)) = impls.iter().find(|(_, existing)| *existing == trait_key) {
        return Err(format!(
          "[{DUPLICATE_TRAIT_IMPL_ERROR}] {}/{} implements {}/{} twice: {other_ns}/{other_def} and {ns}/{def}; a type has at most one implementation of a trait, remove one of them",
          type_key.0, type_key.1, trait_key.0, trait_key.1
        ));
      }
      impls.push(((ns.to_owned(), def.to_owned()), trait_key));
    }
  }

  let mut attached = vec![];
  for ((type_ns, type_def), impls) in by_type {
    let Some(entry) = program.get_mut(&type_ns).and_then(|file| file.defs.get_mut(&type_def)) else {
      continue;
    };
    let refs: Vec<Calcit> = impls
      .iter()
      .map(|((impl_ns, impl_def), _)| impl_reference(&entry.code, impl_ns, impl_def, &type_ns))
      .collect();
    entry.code = attach(&entry.code, &refs);
    attached.push((type_ns, type_def));
  }
  attached.sort();
  Ok(attached)
}
